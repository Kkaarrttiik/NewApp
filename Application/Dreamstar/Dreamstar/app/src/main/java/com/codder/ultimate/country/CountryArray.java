    public static String getCountryCodeFromFlag(String flag) {
        if (flag == null || flag.length() < 2) return "";
        try {
            int codePoint1 = flag.codePointAt(0);
            int codePoint2 = flag.codePointAt(Character.charCount(codePoint1));
            int base = 0x1F1E6; // Regional Indicator Symbol Letter A
            if (codePoint1 >= base && codePoint1 <= 0x1F1FF && codePoint2 >= base && codePoint2 <= 0x1F1FF) {
                char first = (char) ('A' + (codePoint1 - base));
                char second = (char) ('A' + (codePoint2 - base));
                return ("" + first + second).toLowerCase();
            }
        } catch (Exception ignored) {}
        return "";
    }

    public static String getCountryCodeFromUrl(String url) {
        if (url == null || url.isEmpty()) return "";
        try {
            String clean = url.trim();
            if (clean.contains("/")) {
                clean = clean.substring(clean.lastIndexOf("/") + 1);
            }
            if (clean.contains(".")) {
                clean = clean.substring(0, clean.indexOf("."));
            }
            if (clean.length() == 2) {
                return clean.toLowerCase();
            }
        } catch (Exception ignored) {}
        return "";
    }

    public static String getFlagEmojiFromCode(String code) {
        if (code == null || code.trim().length() != 2) return "";
        try {
            String c = code.trim().toUpperCase();
            int first = c.charAt(0) - 'A' + 0x1F1E6;
            int second = c.charAt(1) - 'A' + 0x1F1E6;
            return new String(Character.toChars(first)) + new String(Character.toChars(second));
        } catch (Exception ignored) {}
        return "";
    }

    public static CountryModel findCountryModel(String nameOrCodeOrUrl) {
        if (nameOrCodeOrUrl == null || nameOrCodeOrUrl.trim().isEmpty()) return null;
        String query = nameOrCodeOrUrl.trim();
        List<CountryModel> list = getCountryList();

        // 1. Direct match on flag emoji (e.g. query is "🇮🇳" or contains "🇮🇳")
        for (CountryModel model : list) {
            if ("All".equalsIgnoreCase(model.getName())) continue;
            if (model.getFlag() != null && !model.getFlag().isEmpty()) {
                if (model.getFlag().equals(query) || query.contains(model.getFlag())) {
                    return model;
                }
            }
        }

        // 2. If query is a flag image URL (e.g. "https://flagcdn.com/w160/us.png")
        String codeFromUrl = getCountryCodeFromUrl(query);
        if (!codeFromUrl.isEmpty()) {
            for (CountryModel model : list) {
                if ("All".equalsIgnoreCase(model.getName())) continue;
                String modelCode = getCountryCodeFromFlag(model.getFlag());
                if (modelCode.equalsIgnoreCase(codeFromUrl)) {
                    return model;
                }
            }
        }

        // 3. Match by extracted 2-letter ISO code from flag emoji
        String codeFromFlag = getCountryCodeFromFlag(query);
        if (!codeFromFlag.isEmpty()) {
            for (CountryModel model : list) {
                if ("All".equalsIgnoreCase(model.getName())) continue;
                String modelCode = getCountryCodeFromFlag(model.getFlag());
                if (modelCode.equalsIgnoreCase(codeFromFlag)) {
                    return model;
                }
            }
        }

        // 4. Exact match on country name (e.g. "India")
        for (CountryModel model : list) {
            if ("All".equalsIgnoreCase(model.getName())) continue;
            if (model.getName().equalsIgnoreCase(query)) {
                return model;
            }
        }

        // 5. Exact match on 2-letter ISO code (e.g. "IN", "US")
        for (CountryModel model : list) {
            if ("All".equalsIgnoreCase(model.getName())) continue;
            String code = getCountryCodeFromFlag(model.getFlag());
            if (code.equalsIgnoreCase(query)) {
                return model;
            }
        }

        // 6. Try resolving 2-letter code to English country name via Locale
        String twoLetterCandidate = query.length() == 2 ? query : codeFromUrl;
        if (twoLetterCandidate != null && twoLetterCandidate.length() == 2) {
            try {
                String localeName = new java.util.Locale("", twoLetterCandidate).getDisplayCountry(java.util.Locale.ENGLISH);
                if (localeName != null && !localeName.isEmpty()) {
                    for (CountryModel model : list) {
                        if ("All".equalsIgnoreCase(model.getName())) continue;
                        if (model.getName().equalsIgnoreCase(localeName)) {
                            return model;
                        }
                    }
                    // If not in list, create a synthetic model
                    String flag = getFlagEmojiFromCode(twoLetterCandidate);
                    return new CountryModel(localeName, flag, "", 10);
                }
            } catch (Exception ignored) {}
        }

        // 7. Partial match on country name
        for (CountryModel model : list) {
            if ("All".equalsIgnoreCase(model.getName())) continue;
            if (model.getName().toLowerCase().contains(query.toLowerCase()) ||
                    query.toLowerCase().contains(model.getName().toLowerCase())) {
                return model;
            }
        }

        return null;
    }
